import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
const config=JSON.parse(await readFile(fileURLToPath(new URL('../.private/config.json',import.meta.url)),'utf8'));
const get=path=>fetch(config.origin+path,{signal:AbortSignal.timeout(20000)});
assert.equal((await get('/health')).status,200);
assert.equal((await get('/api/messages')).status,404);
const text='【Synthetic test】code 246810 '+randomUUID();
const upload=()=>fetch(config.origin+'/api/sms',{method:'POST',headers:{Authorization:'Bearer '+config.upload_token,'Content-Type':'application/json'},body:JSON.stringify({message:text,received_at:new Date(Date.now()-590000).toISOString()}),signal:AbortSignal.timeout(20000)});
const uploaded=await upload();assert.equal(uploaded.status,200);assert.equal((await uploaded.json()).accepted,true);
const duplicate=await upload();assert.equal((await duplicate.json()).duplicate,true);
const privatePath='/r/'+config.read_token+'/messages';
const response=await get(privatePath);assert.match(response.headers.get('cache-control')||'',/no-store/);
assert.equal((await response.json()).messages.filter(m=>m.text===text).length,1);
console.log('Health, authorization, upload, read-back and deduplication passed. Waiting for synthetic message expiry…');
await new Promise(resolve=>setTimeout(resolve,11000));
assert.equal((await (await get(privatePath)).json()).messages.some(m=>m.text===text),false);
console.log('Expiry passed. Real iPhone SMS trigger still requires a separate phone test.');
